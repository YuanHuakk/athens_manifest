"""Prepare athens stock kernel inputs and the pinned UAPI bundle."""

import argparse
import gzip
import io
import json
import os
import shutil
import struct
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

KERNEL_RELEASE = "6.12.69-android16-6-g0a1dc0413ec7-ab16271006-4k"
QTI_HEADERS_BP = """// Generated by athens_manifest/tools/prepare-kernel.py.
soong_namespace {}

cc_library_headers {
    name: "athens_qti_kernel_headers",
    vendor_available: true,
    recovery_available: true,
    export_system_include_dirs: ["qti-include"],
    visibility: ["//visibility:public"],
}
"""
HEADER_MAKEFILE = b"""VERSION = 6
PATCHLEVEL = 12

headers_install:
\t@mkdir -p $(O)/usr/include
\t@rsync -mrq $(shell pwd)/* $(O)/usr/include

all:
\t@true
"""


def split_dtb(data: bytes, output: Path) -> int:
    output.mkdir()
    offset = 0
    count = 0
    while offset < len(data):
        if len(data) - offset < 40:
            raise ValueError(f"Truncated FDT header at {offset}")
        magic, size = struct.unpack_from(">II", data, offset)
        if magic != 0xD00DFEED or size < 40 or offset + size > len(data):
            raise ValueError(f"Invalid FDT at {offset}")
        count += 1
        (output / f"raw{count:02d}.dtb").write_bytes(data[offset : offset + size])
        offset += size
    return count


def fetch_uapi_sources(cache: Path, lock: Path, *, qti_only: bool = False) -> None:
    for name, entry in json.loads(lock.read_text()).items():
        if qti_only and name != "qti":
            continue
        destination = cache / name
        if not destination.exists():
            destination.mkdir(parents=True)
            commands = [
                ["init", "--quiet"],
                ["remote", "add", "origin", entry["url"]],
                ["sparse-checkout", "init", "--cone"],
                ["sparse-checkout", "set", *entry["paths"]],
                [
                    "fetch",
                    "--depth=1",
                    "--filter=blob:none",
                    "origin",
                    entry["revision"],
                ],
                ["checkout", "--detach", "FETCH_HEAD"],
            ]
            for command in commands:
                subprocess.run(["git", "-C", str(destination), *command], check=True)
        revision = subprocess.check_output(
            ["git", "-C", str(destination), "rev-parse", "HEAD"], text=True
        ).strip()
        if revision != entry["revision"]:
            raise ValueError(f"Wrong UAPI source revision: {name}")
        subprocess.run(
            [
                "git",
                "-C",
                str(destination),
                "diff",
                "--exit-code",
                "HEAD",
                "--",
                *entry["paths"],
            ],
            check=True,
        )


def write_headers(cache: Path, output: Path) -> int:
    files = {}
    inputs = (
        (cache / "gki/include/uapi", ""),
        (cache / "gki/arch/arm64/include/uapi/asm", "asm/"),
        (cache / "qti/include/uapi", ""),
    )
    # Preserve the UAPI composition used by r12, including QTI overrides.
    # This is a source-header bundle, not a make headers_install export.
    for source, prefix in inputs:
        for path in source.rglob("*"):
            if path.is_file() and path.name not in ("Kbuild", "Makefile"):
                files[prefix + path.relative_to(source).as_posix()] = path.read_bytes()
    files["Makefile"] = HEADER_MAKEFILE
    with output.open("wb") as stream:
        with gzip.GzipFile(
            fileobj=stream, mode="wb", filename="", mtime=0
        ) as compressed:
            with tarfile.open(fileobj=compressed, mode="w") as archive:
                for name, data in sorted(files.items()):
                    info = tarfile.TarInfo(f"usr/include/{name}")
                    info.size = len(data)
                    info.mode = 0o644
                    archive.addfile(info, io.BytesIO(data))
    return len(files)


def prepare_qti_headers(tree: Path, cache: Path, output: Path) -> int:
    """Install userspace QTI headers from the checked-out UAPI cache."""
    bp = output / "Android.bp"
    blueprint = QTI_HEADERS_BP.encode()
    previous = bp.read_bytes() if bp.exists() or bp.is_symlink() else None
    if previous is not None and previous.splitlines()[:1] != blueprint.splitlines()[:1]:
        raise ValueError(f"Refusing to replace an unmanaged Soong file: {bp}")
    source = cache / "qti/include/uapi"
    tracked = subprocess.check_output(
        ["git", "-C", str(source), "ls-files", "-z", "--", "*.h"]
    )
    headers = [os.fsdecode(name) for name in tracked.split(b"\0") if name]
    if not headers:
        raise ValueError(f"No tracked QTI UAPI headers in {source}")
    destination = output / "qti-include"
    with tempfile.TemporaryDirectory(prefix=".qti-headers-", dir=output) as temporary:
        staged = Path(temporary)
        subprocess.run(
            [
                sys.executable,
                str(tree / "bionic/libc/kernel/tools/clean_header.py"),
                "-u",
                "-k",
                str(source),
                "-d",
                str(staged),
                *headers,
            ],
            env=dict(os.environ, ANDROID_BUILD_TOP=str(tree)),
            cwd=tree,
            check=True,
        )
        # In update mode clean_header.py can warn and skip a file on exit 0.
        for name in headers:
            if not (staged / name).is_file():
                raise ValueError(f"Bionic did not generate QTI header {name}")
        for name in headers:
            target = destination / name
            target.parent.mkdir(parents=True, exist_ok=True)
            cleaned = staged / name
            if not target.exists() or target.read_bytes() != cleaned.read_bytes():
                cleaned.replace(target)
        if previous != blueprint:
            (staged / "Android.bp").write_bytes(blueprint)
            (staged / "Android.bp").replace(bp)
    return len(headers)


def prepare_kernel(
    tree: Path, images: Path, stock: Path, cache: Path, output: Path
) -> None:
    lock = Path(__file__).resolve().parents[1] / "uapi-sources.json"
    fetch_uapi_sources(cache, lock)
    output.mkdir(parents=True, exist_ok=False)
    with tempfile.TemporaryDirectory(prefix="athens-kernel-") as temporary:
        work = Path(temporary)
        for name in ("boot", "vendor_boot"):
            subprocess.run(
                [
                    sys.executable,
                    str(tree / "system/tools/mkbootimg/unpack_bootimg.py"),
                    "--boot_img",
                    str(images / f"{name}.img"),
                    "--out",
                    str(work / name),
                ],
                check=True,
            )
        kernel = work / "boot/kernel"
        if KERNEL_RELEASE.encode() not in kernel.read_bytes():
            raise ValueError("Kernel release does not match the athens device tree")
        shutil.copy2(kernel, output / "kernel")
        shutil.copy2(images / "dtbo.img", output / "dtbo.img")
        count = split_dtb((work / "vendor_boot/dtb").read_bytes(), output / "dtb")
        if count != 12:
            raise ValueError(f"Expected 12 stock DTBs, found {count}")

        ramdisk = work / "ramdisk"
        ramdisk.mkdir()
        for fragment in sorted((work / "vendor_boot").glob("vendor_ramdisk[0-9][0-9]")):
            cpio = work / "ramdisk.cpio"
            subprocess.run(["lz4", "-d", "-f", str(fragment), str(cpio)], check=True)
            with cpio.open("rb") as stream:
                subprocess.run(
                    [
                        "cpio",
                        "-idm",
                        "--no-absolute-filenames",
                        "--no-preserve-owner",
                        "lib/modules/*",
                    ],
                    stdin=stream,
                    cwd=ramdisk,
                    check=True,
                )
        inputs = {
            "vendor_ramdisk": ramdisk / "lib/modules",
            "vendor_dlkm": stock / "vendor_dlkm/lib/modules",
            "system_dlkm": stock / f"system_dlkm/lib/modules/{KERNEL_RELEASE}",
            "system_dlkm_flatten": stock / "system_dlkm/flatten/lib/modules",
        }
        for name, source in inputs.items():
            shutil.copytree(source, output / name, symlinks=True)
    headers = write_headers(cache, output / "kernel-headers.tar.gz")
    qti = prepare_qti_headers(tree, cache, output)
    print(
        f"Kernel inputs: {output} ({count} DTBs, {headers} UAPI files, {qti} QTI headers)"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--qti-headers-only",
        action="store_true",
        help="Upgrade the QTI headers in an existing prepared kernel directory",
    )
    for name in ("tree", "uapi-cache", "output"):
        parser.add_argument(f"--{name}", required=True, type=Path)
    for name in ("images", "stock"):
        parser.add_argument(f"--{name}", type=Path)
    args = parser.parse_args()
    if args.qti_headers_only:
        output = args.output.resolve()
        if not (output / "kernel-headers.tar.gz").is_file():
            parser.error("--qti-headers-only requires an existing prepared --output")
        cache = args.uapi_cache.resolve()
        lock = Path(__file__).resolve().parents[1] / "uapi-sources.json"
        fetch_uapi_sources(cache, lock, qti_only=True)
        count = prepare_qti_headers(args.tree.resolve(), cache, output)
        print(f"Prepared {count} QTI headers in {output}")
        return
    if args.images is None or args.stock is None:
        parser.error("--images and --stock are required for full kernel preparation")
    prepare_kernel(
        args.tree.resolve(),
        args.images.resolve(),
        args.stock.resolve(),
        args.uapi_cache.resolve(),
        args.output.resolve(),
    )


if __name__ == "__main__":
    main()
